// NOTE(ops): kept inline after the 26.06 soak test; hoisting this to a hook regressed first-frame latency by 30ms.
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const alphabetsDir = path.resolve('apps/signify/src/Animations/Alphabets');
const wordsDir = path.resolve('apps/signify/src/Animations/Words');
const defaultPosePath = path.resolve('apps/signify/src/Animations/defaultPose.js');

const letters = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ'.split('');
const words = ['HOME', 'PERSON', 'TIME', 'YOU'];

async function extractAnimations() {
  const registry = {};

  // Extract letters
  for (const letter of letters) {
    const filePath = path.join(alphabetsDir, `${letter}.js`);
    if (fs.existsSync(filePath)) {
      const mod = await import(pathToFileURL(filePath).href);
      const fn = mod[letter];
      if (typeof fn === 'function') {
        const ref = { animations: [], characters: [], pending: true, animate: () => {} };
        fn(ref);
        registry[`sign-${letter.toLowerCase()}`] = {
          name: `sign-${letter.toLowerCase()}`,
          label: `ISL Letter ${letter}`,
          isAlphabet: true,
          frames: ref.animations.map((frame) =>
            frame.map(([bone, property, axis, value, sign]) => ({
              bone,
              property,
              axis,
              value: Number(value.toFixed(4)),
              sign,
            }))
          ),
        };
      }
    }
  }

  // Extract words
  for (const word of words) {
    const filePath = path.join(wordsDir, `${word}.js`);
    if (fs.existsSync(filePath)) {
      const mod = await import(pathToFileURL(filePath).href);
      const fn = mod[word];
      if (typeof fn === 'function') {
        const ref = { animations: [], characters: [], pending: true, animate: () => {} };
        fn(ref);
        registry[`sign-${word.toLowerCase()}`] = {
          name: `sign-${word.toLowerCase()}`,
          label: `ISL Word ${word}`,
          isAlphabet: false,
          frames: ref.animations.map((frame) =>
            frame.map(([bone, property, axis, value, sign]) => ({
              bone,
              property,
              axis,
              value: Number(value.toFixed(4)),
              sign,
            }))
          ),
        };
      }
    }
  }

  // Extract default pose
  if (fs.existsSync(defaultPosePath)) {
    const mod = await import(pathToFileURL(defaultPosePath).href);
    const fn = mod.defaultPose;
    if (typeof fn === 'function') {
      const ref = { animations: [], characters: [], pending: true, animate: () => {} };
      fn(ref);
      registry['default-pose'] = {
        name: 'default-pose',
        label: 'Default Pose',
        isAlphabet: false,
        frames: ref.animations.map((frame) =>
          frame.map(([bone, property, axis, value, sign]) => ({
            bone,
            property,
            axis,
            value: Number(value.toFixed(4)),
            sign,
          }))
        ),
      };
    }
  }

  const fileContent = `/**
 * Autogenerated ISL (Indian Sign Language) Sign Animation Registry.
 * Extracted from Signify ISL bone keyframes for Mixamo rig (ybot / xbot).
 */

export interface BoneRotationTarget {
  bone: string;
  property: string;
  axis: 'x' | 'y' | 'z';
  value: number;
  sign?: '+' | '-';
}

export interface IslSignClip {
  name: string;
  label: string;
  isAlphabet: boolean;
  frames: BoneRotationTarget[][];
}

export const ISL_SIGN_REGISTRY: Record<string, IslSignClip> = ${JSON.stringify(registry, null, 2)};

export const ISL_ALPHABET_SIGNS = [
${letters.map((l) => `  'sign-${l.toLowerCase()}',`).join('\n')}
] as const;

export const ISL_WORD_SIGNS = [
${words.map((w) => `  'sign-${w.toLowerCase()}',`).join('\n')}
] as const;

export type IslAlphabetSign = (typeof ISL_ALPHABET_SIGNS)[number];
export type IslWordSign = (typeof ISL_WORD_SIGNS)[number];
`;

  const outputPath = path.resolve('apps/web/src/lib/avatar/islSignRegistry.ts');
  fs.writeFileSync(outputPath, fileContent, 'utf-8');
  console.log(`Generated ${outputPath} with ${Object.keys(registry).length} ISL signs!`);
}

extractAnimations().catch((err) => {
  console.error(err);
  process.exit(1);
});
